#Requires -Version 7.0
<#
.SYNOPSIS
  Bootstrap the all-in-one dsh-mobile + GateAway Docker stack.

.DESCRIPTION
  Generates local secrets, prepares deploy/.env, builds the custom images, starts
  GateAway, creates/reuses the dsh-mobile tenant and client key, registers the
  deepseek-flash model, then starts the app stack.

  Secrets are written to deploy/secrets/ (git-ignored) and deploy/.env
  (git-ignored). They are never printed.

.PARAMETER Force
  Stop existing dsh-mobile / llm-gateaway stacks and regenerate local secrets.

.PARAMETER ExistingGateway
  Reuse the existing llm-gateaway_pgdata volume and its client keys/audit data.

.PARAMETER SkipBuild
  Do not build images; fail if a required image is missing.

.PARAMETER GatewayRepo
  Path to the LLM-GateAway checkout. Defaults to GATEWAY_REPO from .env or
  ../../LLM-GateAway relative to deploy/.
#>
[CmdletBinding()]
param(
    [switch]$Force,
    [switch]$ExistingGateway,
    [switch]$SkipBuild,
    [string]$GatewayRepo
)

$ErrorActionPreference = 'Stop'

$DeployDir = $PSScriptRoot
$ComposeFile = Join-Path $DeployDir 'docker-compose.with-gateaway.yml'
$DefaultComposeFile = Join-Path $DeployDir 'docker-compose.yml'
$EnvFile = Join-Path $DeployDir '.env'
$ExampleFile = Join-Path $DeployDir '.env.example'
$SecretsDir = Join-Path $DeployDir 'secrets'
$Utf8NoBom = [System.Text.UTF8Encoding]::new($false)

function Write-Step {
    param([string]$Message)
    Write-Host "==> $Message"
}

function Stop-WithError {
    param([string]$Message)
    Write-Host "ERROR: $Message" -ForegroundColor Red
    exit 1
}

function Read-DotEnv {
    param([string]$Path)
    $map = [ordered]@{}
    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
        return $map
    }
    foreach ($line in Get-Content -LiteralPath $Path) {
        if ($line -match '^\s*#' -or $line -match '^\s*$') { continue }
        $match = [regex]::Match($line, '^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$')
        if (-not $match.Success) { continue }
        $key = $match.Groups[1].Value
        $value = $match.Groups[2].Value.Trim()
        if ($value.Length -ge 2) {
            $quoted =
                ($value.StartsWith('"') -and $value.EndsWith('"')) -or
                ($value.StartsWith("'") -and $value.EndsWith("'"))
            if ($quoted) { $value = $value.Substring(1, $value.Length - 2) }
        }
        $map[$key] = $value
    }
    return $map
}

function Write-DotEnv {
    param(
        [string]$Path,
        [System.Collections.Specialized.OrderedDictionary]$Map
    )
    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add('# Generated by deploy/bootstrap.ps1. Do not commit.')
    $lines.Add('# Secrets are stored in deploy/secrets/ (git-ignored).')
    $lines.Add('')
    foreach ($key in $Map.Keys) {
        $lines.Add("$key=$($Map[$key])")
    }
    [System.IO.File]::WriteAllLines($Path, $lines, $Utf8NoBom)
}

function Set-Default {
    param(
        [System.Collections.Specialized.OrderedDictionary]$Map,
        [string]$Key,
        [string]$Value
    )
    if (-not $Map.Contains($Key) -or [string]::IsNullOrWhiteSpace([string]$Map[$Key])) {
        $Map[$Key] = $Value
    }
}

function New-RandomToken {
    $bytes = [byte[]]::new(32)
    [System.Security.Cryptography.RandomNumberGenerator]::Fill($bytes)
    return [Convert]::ToBase64String($bytes).TrimEnd('=').Replace('+', '-').Replace('/', '_')
}

function New-RandomHex {
    $bytes = [byte[]]::new(24)
    [System.Security.Cryptography.RandomNumberGenerator]::Fill($bytes)
    return [Convert]::ToHexString($bytes).ToLowerInvariant()
}

function Get-ExistingSecret {
    param(
        [string]$FileName,
        [string]$EnvKey,
        [string]$Hint
    )
    $path = Join-Path $SecretsDir $FileName
    if (Test-Path -LiteralPath $path -PathType Leaf) {
        $value = (Get-Content -LiteralPath $path -Raw).Trim()
        if (-not [string]::IsNullOrWhiteSpace($value)) { return $value }
    }
    if ($envMap.Contains($EnvKey) -and -not [string]::IsNullOrWhiteSpace([string]$envMap[$EnvKey])) {
        $value = [string]$envMap[$EnvKey]
        [System.IO.File]::WriteAllText($path, $value, $Utf8NoBom)
        return $value
    }
    Stop-WithError "$Hint. Put it in deploy/.env or deploy/secrets/$FileName and rerun."
}

function Get-OrCreateSecret {
    param(
        [string]$FileName,
        [string]$EnvKey,
        [scriptblock]$Generator
    )
    $path = Join-Path $SecretsDir $FileName
    if (-not $Force -and (Test-Path -LiteralPath $path -PathType Leaf)) {
        $value = (Get-Content -LiteralPath $path -Raw).Trim()
        if (-not [string]::IsNullOrWhiteSpace($value)) { return $value }
    }
    if (-not $Force -and $envMap.Contains($EnvKey) -and -not [string]::IsNullOrWhiteSpace([string]$envMap[$EnvKey])) {
        $value = [string]$envMap[$EnvKey]
        [System.IO.File]::WriteAllText($path, $value, $Utf8NoBom)
        return $value
    }
    $value = & $Generator
    [System.IO.File]::WriteAllText($path, $value, $Utf8NoBom)
    return $value
}

function Invoke-Compose {
    param([string[]]$ComposeArgs)
    & docker compose -f $ComposeFile @ComposeArgs
    if ($LASTEXITCODE -ne 0) {
        Stop-WithError "docker compose $($ComposeArgs -join ' ') failed"
    }
}

function Test-Image {
    param([string]$Name)
    & docker image inspect $Name *> $null
    return $LASTEXITCODE -eq 0
}

function Assert-RequiredImage {
    param([string]$Image)
    if (-not (Test-Image $Image)) {
        Stop-WithError "Image '$Image' is missing; rerun without -SkipBuild"
    }
}

function Wait-Http {
    param(
        [string]$Url,
        [int]$Attempts = 60,
        [int]$DelaySeconds = 2,
        [switch]$SkipCertificateCheck
    )
    for ($attempt = 1; $attempt -le $Attempts; $attempt++) {
        try {
            $request = @{
                Uri = $Url
                TimeoutSec = 5
                SkipHttpErrorCheck = $true
            }
            if ($SkipCertificateCheck) { $request.SkipCertificateCheck = $true }
            $response = Invoke-WebRequest @request
            if ($response.StatusCode -ge 200 -and $response.StatusCode -lt 300) {
                return $response
            }
        } catch {
            # Keep retrying until the bound.
        }
        Start-Sleep -Seconds $DelaySeconds
    }
    Stop-WithError "Timed out waiting for $Url"
}

$Docker = Get-Command docker -ErrorAction SilentlyContinue
if ($null -eq $Docker) { Stop-WithError 'docker is required on PATH' }
$Git = Get-Command git -ErrorAction SilentlyContinue
if ($null -eq $Git) { Stop-WithError 'git is required on PATH' }
& docker compose version *> $null
if ($LASTEXITCODE -ne 0) { Stop-WithError 'docker compose (v2) is required' }

$envExisted = Test-Path -LiteralPath $EnvFile -PathType Leaf
$envMap = if ($envExisted) { Read-DotEnv $EnvFile } else { Read-DotEnv $ExampleFile }

# Clear placeholders copied from .env.example.
foreach ($key in @('BRIDGE_SECRET', 'GATEWAY_MASTER_KEY', 'POSTGRES_PASSWORD', 'GATEAWAY_API_KEY', 'GATEWAY_DEEPSEEK_API_KEY')) {
    if ($envMap.Contains($key) -and [string]$envMap[$key] -match '^(change-me|replace-with|your-)') {
        $envMap[$key] = ''
    }
}

New-Item -ItemType Directory -Force -Path $SecretsDir | Out-Null

Write-Step 'resolving LLM-GateAway checkout'
$repoCandidate = $GatewayRepo
if ([string]::IsNullOrWhiteSpace($repoCandidate)) {
    if ($envMap.Contains('GATEWAY_REPO') -and -not [string]::IsNullOrWhiteSpace([string]$envMap['GATEWAY_REPO'])) {
        $repoCandidate = [string]$envMap['GATEWAY_REPO']
    } else {
        $repoCandidate = '../../LLM-GateAway'
    }
}
if (-not [System.IO.Path]::IsPathRooted($repoCandidate)) {
    $repoCandidate = Join-Path $DeployDir $repoCandidate
}
$GatewayRepoPath = [System.IO.Path]::GetFullPath($repoCandidate)
if (-not (Test-Path -LiteralPath (Join-Path $GatewayRepoPath 'Dockerfile') -PathType Leaf)) {
    if (Test-Path -LiteralPath $GatewayRepoPath) {
        $existing = @(Get-ChildItem -LiteralPath $GatewayRepoPath -Force -ErrorAction SilentlyContinue)
        if ($existing.Count -gt 0) {
            Stop-WithError "'$GatewayRepoPath' exists but is not an LLM-GateAway checkout"
        }
    }
    Write-Step "cloning LLM-GateAway into $GatewayRepoPath"
    $parent = Split-Path -Parent $GatewayRepoPath
    if (-not (Test-Path -LiteralPath $parent)) {
        New-Item -ItemType Directory -Force -Path $parent | Out-Null
    }
    & git clone https://github.com/mrchipset/LLM-GateAway.git $GatewayRepoPath
    if ($LASTEXITCODE -ne 0) { Stop-WithError "git clone failed for $GatewayRepoPath" }
}
if (-not (Test-Path -LiteralPath (Join-Path $GatewayRepoPath 'ui/Dockerfile') -PathType Leaf)) {
    Stop-WithError "'$GatewayRepoPath' has no ui/Dockerfile; point -GatewayRepo at the checkout root"
}
$GatewayRepoForCompose = $GatewayRepoPath.Replace('\', '/')

if ($Force) {
    Write-Warning 'Force: stopping existing stacks; secrets will be refreshed (existing Gateway keeps DB credentials).'
    & docker compose -f $DefaultComposeFile down 2>$null | Out-Null
    & docker compose -f $ComposeFile down 2>$null | Out-Null
    $gatewayCompose = Join-Path $GatewayRepoPath 'docker-compose.yml'
    if (Test-Path -LiteralPath $gatewayCompose -PathType Leaf) {
        & docker compose -f $gatewayCompose down 2>$null | Out-Null
    }
    if (-not $ExistingGateway) {
        Write-Warning 'Force recreates the fresh Gateway DB volume (dsh-mobile-gateway-pgdata); app volumes are kept.'
        & docker volume inspect 'dsh-mobile-gateway-pgdata' *> $null
        if ($LASTEXITCODE -eq 0) {
            & docker volume rm 'dsh-mobile-gateway-pgdata' *> $null
            if ($LASTEXITCODE -ne 0) {
                Stop-WithError 'could not remove dsh-mobile-gateway-pgdata; stop containers using it, or rerun with -ExistingGateway'
            }
        }
    }
} elseif ($ExistingGateway) {
    Write-Warning 'ExistingGateway assumes the old llm-gateaway stack is stopped; use -Force to stop it automatically.'
}

Write-Step 'preparing secrets'
$BridgeSecret = Get-OrCreateSecret -FileName 'bridge.secret' -EnvKey 'BRIDGE_SECRET' -Generator { New-RandomToken }
if ($ExistingGateway) {
    # The existing volume already has this password and provider keys encrypted
    # with the existing master key. Generating new values would break it.
    $PostgresPassword = Get-ExistingSecret -FileName 'postgres.password' -EnvKey 'POSTGRES_PASSWORD' `
        -Hint 'Existing Gateway volume requires the matching POSTGRES_PASSWORD'
    $MasterKey = Get-ExistingSecret -FileName 'gateway.master.key' -EnvKey 'GATEWAY_MASTER_KEY' `
        -Hint 'Existing Gateway volume requires the matching GATEWAY_MASTER_KEY'
} else {
    $MasterKey = Get-OrCreateSecret -FileName 'gateway.master.key' -EnvKey 'GATEWAY_MASTER_KEY' -Generator { New-RandomToken }
    $PostgresPassword = Get-OrCreateSecret -FileName 'postgres.password' -EnvKey 'POSTGRES_PASSWORD' -Generator { New-RandomHex }
}

$deepseekKey = $env:GATEWAY_DEEPSEEK_API_KEY
if ([string]::IsNullOrWhiteSpace($deepseekKey) -and $envMap.Contains('GATEWAY_DEEPSEEK_API_KEY')) {
    $deepseekKey = [string]$envMap['GATEWAY_DEEPSEEK_API_KEY']
}
$deepseekFile = Join-Path $SecretsDir 'gateway.deepseek.key'
if ([string]::IsNullOrWhiteSpace($deepseekKey) -and (Test-Path -LiteralPath $deepseekFile -PathType Leaf)) {
    $deepseekKey = (Get-Content -LiteralPath $deepseekFile -Raw).Trim()
}
if ([string]::IsNullOrWhiteSpace($deepseekKey)) {
    Stop-WithError 'GATEWAY_DEEPSEEK_API_KEY is required. Set $env:GATEWAY_DEEPSEEK_API_KEY (or put it in deploy/.env), then rerun.'
}
[System.IO.File]::WriteAllText($deepseekFile, $deepseekKey, $Utf8NoBom)

$envMap['BRIDGE_SECRET'] = $BridgeSecret
$envMap['GATEWAY_MASTER_KEY'] = $MasterKey
$envMap['POSTGRES_PASSWORD'] = $PostgresPassword
$envMap['GATEWAY_DEEPSEEK_API_KEY'] = $deepseekKey
$envMap['GATEWAY_REPO'] = $GatewayRepoForCompose

if ($ExistingGateway) {
    $envMap['GATEWAY_PGDATA_VOLUME'] = 'llm-gateaway_pgdata'
    $envMap['GATEWAY_PGDATA_EXTERNAL'] = 'true'
} elseif ($Force -or -not $envExisted -or -not $envMap.Contains('GATEWAY_PGDATA_VOLUME') -or [string]::IsNullOrWhiteSpace([string]$envMap['GATEWAY_PGDATA_VOLUME'])) {
    $envMap['GATEWAY_PGDATA_VOLUME'] = 'dsh-mobile-gateway-pgdata'
    $envMap['GATEWAY_PGDATA_EXTERNAL'] = 'false'
}

Set-Default $envMap 'GATEWAY_PGDATA_VOLUME' 'llm-gateaway_pgdata'
Set-Default $envMap 'GATEWAY_PGDATA_EXTERNAL' 'true'
Set-Default $envMap 'GATEWAY_ENVIRONMENT' 'production'
Set-Default $envMap 'GATEWAY_LOG_LEVEL' 'INFO'
Set-Default $envMap 'GATEWAY_UI_PORT' '8080'
Set-Default $envMap 'GATEWAY_OPENAI_BASE_URL' 'https://api.openai.com/v1'
Set-Default $envMap 'GATEWAY_DEEPSEEK_BASE_URL' 'https://api.deepseek.com'
Set-Default $envMap 'GATEWAY_REQUEST_TIMEOUT_SECONDS' '60'
Set-Default $envMap 'GATEWAY_CONNECT_TIMEOUT_SECONDS' '10'
Set-Default $envMap 'GATEWAY_MAX_RETRIES' '2'
Set-Default $envMap 'GATEWAY_AUDIT_ENABLED' 'false'
Set-Default $envMap 'GATEWAY_AUDIT_MAX_CONTENT_BYTES' '262144'
Set-Default $envMap 'GATEWAY_AUDIT_WRITE_TIMEOUT_SECONDS' '2'
Set-Default $envMap 'GATEWAY_FAKE_PROVIDER_ENABLED' 'false'

$uiPort = [string]$envMap['GATEWAY_UI_PORT']
if ([string]::IsNullOrWhiteSpace($uiPort)) { $uiPort = '8080' }

Write-DotEnv -Path $EnvFile -Map $envMap
$env:GATEWAY_REPO = $GatewayRepoForCompose
$env:GATEWAY_PGDATA_VOLUME = [string]$envMap['GATEWAY_PGDATA_VOLUME']
$env:GATEWAY_PGDATA_EXTERNAL = [string]$envMap['GATEWAY_PGDATA_EXTERNAL']

if ($SkipBuild) {
    Write-Step 'skipping builds (-SkipBuild); checking required images'
    foreach ($image in @(
            'postgres:16-alpine',
            'llm-gateaway-backend:local',
            'llm-gateaway-ui:local',
            'dsh-mobile-bridge:local',
            'dsh-mobile-web:local',
            'funasr-openai-api:cpu-2026-10'
        )) {
        Assert-RequiredImage $image
    }
} else {
    Write-Step 'building GateAway backend/ui (local source)'
    Invoke-Compose -ComposeArgs @('build', 'backend', 'ui')
    Write-Step 'building dsh-mobile bridge/web'
    Invoke-Compose -ComposeArgs @('build', 'bridge', 'web')
    if (-not (Test-Image 'funasr-openai-api:cpu-2026-10')) {
        Write-Step 'STT image missing; building it (slow)'
        Invoke-Compose -ComposeArgs @('build', 'stt')
    }
}

Write-Step 'starting GateAway (postgres, migrate, backend, ui)'
Invoke-Compose -ComposeArgs @('up', '-d', 'postgres', 'migrate', 'backend', 'ui')
Wait-Http -Url "http://127.0.0.1:$uiPort/readyz" -Attempts 90 -DelaySeconds 2 | Out-Null

function Invoke-AdminApi {
    param(
        [string]$Method,
        [string]$Path,
        [object]$Body
    )
    $request = @{
        Method = $Method
        Uri = "http://127.0.0.1:$uiPort$Path"
        Headers = @{ Authorization = "Bearer $MasterKey" }
        SkipHttpErrorCheck = $true
        TimeoutSec = 30
    }
    if ($null -ne $Body) {
        $request.ContentType = 'application/json'
        $request.Body = ($Body | ConvertTo-Json -Compress -Depth 5)
    }
    return Invoke-WebRequest @request
}

Write-Step 'ensuring tenant dsh-mobile'
$tenantResponse = Invoke-AdminApi -Method POST -Path '/api/v1/tenants' -Body @{ name = 'dsh-mobile' }
$tenantId = $null
if ($tenantResponse.StatusCode -eq 201) {
    $tenantId = ($tenantResponse.Content | ConvertFrom-Json).id
} elseif ($tenantResponse.StatusCode -eq 409) {
    $listResponse = Invoke-AdminApi -Method GET -Path '/api/v1/tenants?limit=100' -Body $null
    if ($listResponse.StatusCode -eq 200) {
        $tenant = ($listResponse.Content | ConvertFrom-Json).items |
            Where-Object { $_.name -eq 'dsh-mobile' } |
            Select-Object -First 1
        if ($null -ne $tenant) { $tenantId = $tenant.id }
    }
}
if ([string]::IsNullOrWhiteSpace([string]$tenantId)) {
    Stop-WithError "could not create or find tenant 'dsh-mobile' (HTTP $($tenantResponse.StatusCode))"
}

$clientKeyFile = Join-Path $SecretsDir 'gateway.client.key'
$clientKey = $null
if ($ExistingGateway -or -not $Force) {
    if ($envMap.Contains('GATEAWAY_API_KEY') -and -not [string]::IsNullOrWhiteSpace([string]$envMap['GATEAWAY_API_KEY'])) {
        $clientKey = [string]$envMap['GATEAWAY_API_KEY']
    } elseif (Test-Path -LiteralPath $clientKeyFile -PathType Leaf) {
        $clientKey = (Get-Content -LiteralPath $clientKeyFile -Raw).Trim()
    }
}
if ([string]::IsNullOrWhiteSpace($clientKey)) {
    Write-Step 'creating one-time Gateway client key'
    $keyResponse = Invoke-AdminApi -Method POST -Path '/api/v1/keys' -Body @{
        name = 'dsh-mobile'
        tenant_id = $tenantId
    }
    if ($keyResponse.StatusCode -ne 201) {
        Stop-WithError "could not create Gateway client key (HTTP $($keyResponse.StatusCode))"
    }
    $clientKey = ($keyResponse.Content | ConvertFrom-Json).key
    if ([string]::IsNullOrWhiteSpace([string]$clientKey)) {
        Stop-WithError 'Gateway key response did not contain a plaintext key'
    }
    [System.IO.File]::WriteAllText($clientKeyFile, $clientKey, $Utf8NoBom)
    Write-Step 'client key saved to deploy/secrets/gateway.client.key'
} else {
    [System.IO.File]::WriteAllText($clientKeyFile, $clientKey, $Utf8NoBom)
    Write-Step 'reusing existing Gateway client key'
}
$envMap['GATEAWAY_API_KEY'] = $clientKey

Write-Step 'ensuring model deepseek-flash'
$modelResponse = Invoke-AdminApi -Method GET -Path '/api/v1/models?limit=100' -Body $null
$modelExists = $false
if ($modelResponse.StatusCode -eq 200) {
    $modelExists = @(
        ($modelResponse.Content | ConvertFrom-Json).items |
            Where-Object { $_.id -eq 'deepseek-flash' }
    ).Count -gt 0
}
if (-not $modelExists) {
    $createModel = Invoke-AdminApi -Method POST -Path '/api/v1/models' -Body @{
        id = 'deepseek-flash'
        provider = 'deepseek'
        upstream_model = 'deepseek-flash'
        enabled = $true
    }
    if ($createModel.StatusCode -notin @(201, 409)) {
        Stop-WithError "could not register deepseek-flash (HTTP $($createModel.StatusCode)); check GATEWAY_DEEPSEEK_API_KEY"
    }
    Write-Step 'registered model deepseek-flash'
} else {
    Write-Step 'model deepseek-flash already registered'
}

# Persist the final key as well; the app stack reads it from .env.
Write-DotEnv -Path $EnvFile -Map $envMap

Write-Step 'starting app stack (stt, bridge, web)'
Invoke-Compose -ComposeArgs @('up', '-d', 'stt', 'bridge', 'web')

Write-Step 'waiting for Bridge/Caddy readiness'
$ready = $false
for ($attempt = 1; $attempt -le 300; $attempt++) {
    try {
        $healthResponse = Invoke-WebRequest -Uri 'https://127.0.0.1:8443/api/health' `
            -SkipCertificateCheck -SkipHttpErrorCheck -TimeoutSec 5
        if ($healthResponse.StatusCode -eq 200) {
            $health = $healthResponse.Content | ConvertFrom-Json
            if ($health.ok -eq $true -and $health.agent -eq 'ready' -and $health.stt.reachable -eq $true -and $health.audio.ffmpeg -eq $true) {
                $ready = $true
                break
            }
        }
    } catch {
        # Keep retrying until the bound.
    }
    Start-Sleep -Seconds 2
}
if (-not $ready) {
    Stop-WithError 'Bridge did not become ready within ~10 minutes; inspect: docker compose -f deploy/docker-compose.with-gateaway.yml logs bridge stt backend'
}

Write-Host ''
Write-Host 'Bootstrap complete.'
Write-Host "  App:          https://127.0.0.1:8443 (LAN: https://<LAN-IP>:8443)"
Write-Host "  Gateway UI:   http://127.0.0.1:$uiPort"
Write-Host "  Secrets:      $SecretsDir"
Write-Host '  Key files:    bridge.secret, gateway.master.key, gateway.client.key, postgres.password, gateway.deepseek.key'
Write-Host '  Secrets and deploy/.env are git-ignored; do not commit or share them.'
